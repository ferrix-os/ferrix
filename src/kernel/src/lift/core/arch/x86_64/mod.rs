/// # Safety
/// `source` is an arena page's address, for `out`'s length.
pub unsafe fn copy_mc(out: &mut [u8], source: u64) -> Copied {
    // SAFETY: the caller says `source` holds `out`'s length, in the arena, which
    // `out` is not part of.
    unsafe { core::ptr::copy_nonoverlapping(source as *const u8, out.as_mut_ptr(), out.len()) };
    Copied { left: 0, page: 0 }
}
