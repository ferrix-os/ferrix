pub fn user_hwcaps() -> (u64, u64) {
    use core::sync::atomic::{AtomicU64, Ordering};
    // Every `execve` asks; `CPUID` is a virtual machine exit (cpu::extended_state_components).
    // Bit 63 says it has been read.
    const KNOWN: u64 = 1 << 63;
    static EDX: AtomicU64 = AtomicU64::new(0);
    let kept = EDX.load(Ordering::Relaxed);
    if kept & KNOWN != 0 {
        return (kept & !KNOWN, 0);
    }
    // SAFETY: CPUID is unprivileged.
    let leaf = unsafe { core::arch::x86_64::__cpuid(1) };
    EDX.store(u64::from(leaf.edx) | KNOWN, Ordering::Relaxed);
    (u64::from(leaf.edx), 0)
}
pub fn cpuid(leaf: u32, subleaf: u32) -> Option<[u32; 4]> {
    // SAFETY: CPUID is unprivileged.
    let r = unsafe { core::arch::x86_64::__cpuid_count(leaf, subleaf) };
    Some([r.eax, r.ebx, r.ecx, r.edx])
}
