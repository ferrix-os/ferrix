fn read_cntvct() -> u64 {
    let value: u64;
    // SAFETY: CNTVCT_EL0 is open to EL0 where the kernel set CNTKCTL_EL1.EL0VCTEN, which
    // the vDSO's own read rests on; `isb` keeps the read from moving earlier.
    unsafe {
        core::arch::asm!("isb", "mrs {}, cntvct_el0", out(reg) value, options(nomem, nostack, preserves_flags));
    }
    value
}
