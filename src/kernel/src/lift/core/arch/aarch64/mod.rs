/// The kernel reads the identification registers, which EL0 cannot; it answers once, and
/// the answer does not change while linuxd runs.
pub fn user_hwcaps() -> (u64, u64) {
    use core::sync::atomic::{AtomicU64, Ordering};
    const KNOWN: u64 = 1 << 63;
    static ONE: AtomicU64 = AtomicU64::new(0);
    static TWO: AtomicU64 = AtomicU64::new(0);
    let kept = ONE.load(Ordering::Relaxed);
    if kept & KNOWN != 0 {
        return (kept & !KNOWN, TWO.load(Ordering::Relaxed));
    }
    let hwcap = crate::sys::clock(ferrix_native_abi::lift::CLOCK_HWCAP);
    let hwcap2 = crate::sys::clock(ferrix_native_abi::lift::CLOCK_HWCAP2);
    TWO.store(hwcap2, Ordering::Relaxed);
    ONE.store(hwcap | KNOWN, Ordering::Relaxed);
    (hwcap, hwcap2)
}
