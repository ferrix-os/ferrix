/// A program's new code: the kernel's fill made it visible, and its own `ic ivau` serves
/// from EL0 (`SCTLR_EL1.UCI`), as the kernel's way does.
pub fn sync_instructions(start: u64, len: u64) {
    let line = 64_u64;
    let mut at = start & !(line - 1);
    while at < start.saturating_add(len) {
        // SAFETY: a clean and an invalidate by a mapped address of this program's arena;
        // neither changes anything a program holds.
        unsafe {
            core::arch::asm!("dc cvau, {0}", "ic ivau, {0}", in(reg) at, options(nostack, preserves_flags));
        }
        at += line;
    }
    // SAFETY: barriers.
    unsafe {
        core::arch::asm!("dsb ish", "isb", options(nostack, preserves_flags));
    }
}

