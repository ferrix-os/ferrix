/// The interrupt QEMU's `virt` machine wires its PL011 to: SPI 1.
///
/// **A stand-in, as [`console`]'s address is.** This architecture boots through
/// ACPI and reads no SPCR table, which is where the console's interrupt belongs
/// to come from; when the SPCR is parsed, its GSIV replaces this, and the
/// address beside it.
const QEMU_VIRT_UART0_INTERRUPT: u32 = 33;

/// The GIC interrupt the console port receives on, or `None` for a
/// `ramoops` record, which receives nothing -- and on whose machine SPI 1 is
/// some other device's line -- or for the 16550, which is polled.
pub(crate) fn console_receive_irq(_view: &BootView<'_>) -> Option<u32> {
    (!console::is_ramoops() && !console::is_ns16550()).then_some(QEMU_VIRT_UART0_INTERRUPT)
}

/// Enable the console port's receive interrupt `irq`, at the GIC and in the
/// port. On the calling processor, like the timer's: a shared interrupt goes
/// to the core that enables it.
pub(crate) fn enable_console_receive(irq: u32) {
    gic::enable(irq);
    console::enable_receive_interrupt();
}

/// `AT_HWCAP` and `AT_HWCAP2` for a program started on this machine: what the
/// core's identification registers say it has, in the bits
/// `arch/arm64/include/uapi/asm/hwcap.h` numbers, and only the features a
/// program can use without more from the kernel. See `ferrix_linux_abi::hwcap`.
pub(crate) fn user_hwcaps() -> (u64, u64) {
    use ferrix_linux_abi::hwcap::aarch64::{IdRegisters, hwcap, hwcap2};
    let ids = IdRegisters {
        pfr0: cpu::read_id_aa64pfr0(),
        isar0: cpu::read_id_aa64isar0(),
        isar1: cpu::read_id_aa64isar1(),
    };
    (hwcap(ids), hwcap2(ids))
}

