/// Whether [`flush_tlb`] reaches every processor's TLB.
///
/// Yes, as on AArch64: `TLBIALLIS` is broadcast to the inner shareable
/// domain, and the `dsb ish` after it waits for every core to finish.
pub(crate) const TLB_FLUSH_IS_BROADCAST: bool = true;

/// Invalidate the translation of the page holding `address` — on every core,
/// as [`flush_tlb`] does.
///
/// An address past four gigabytes cannot be a translation here; asked for one,
/// this flushes everything rather than a truncated page.
pub(crate) fn flush_tlb_page(address: u64) {
    match u32::try_from(address) {
        Ok(page) => cpu::flush_tlb_page(page),
        Err(_) => cpu::flush_tlb(),
    }
}

