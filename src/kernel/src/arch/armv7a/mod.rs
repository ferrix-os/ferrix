/// Fold an ARMv7-A (EABI) system call number onto the call it means.
///
/// The EABI table predates the generic one and kept much of what the generic
/// one dropped, so this architecture has `open` and `fork` where AArch64 does
/// not. It also has calls neither 64-bit architecture has: the `64` forms that
/// carry an offset a 32-bit register cannot, and the ARM-private range at
/// `0x0f0000`, which is why a valid number here is *not* bounded by the size
/// of the shared table. This is the only place in the kernel that knows which
/// of the three tables applies; `crate::syscall` dispatches on the answer.
///
/// The number is a program's, and the table is a `match` the compiler makes a
/// jump table of, so it is bounded and clamped first: a processor that
/// mispredicts the table's own bounds check then jumps through slot zero
/// rather than through whatever lies past the table (Spectre variant 1).
/// Each of the two ranges is bounded by its own end, and a misprediction of
/// which range the number is in lands on the start of the other.
pub(crate) fn decode_syscall(number: usize) -> Option<Syscall> {
    let base = nr::arm::ARM_PRIVATE_BASE;
    let number = match number.checked_sub(base) {
        Some(private) => base + super::nospec_index(private, nr::ARM_PRIVATE_END - base)?,
        None => super::nospec_index(number, nr::ARM_END)?,
    };
    nr::from_arm(number)
}

/// The `AUDIT_ARCH_*` token a system call carries in `seccomp_data.arch`:
/// `EM_ARM` | `__AUDIT_ARCH_LE`. One ABI here.
pub(crate) const fn audit_arch(abi: crate::trap::Abi) -> u32 {
    let _ = abi;
    0x4000_0028
}

/// The value to put in the return register of a call that is not run, so that
/// the frame reads as it did when the program made the call: Linux's
/// `syscall_rollback`. `r7` still holds the number, and `r0` held the first
/// argument (`docs/SECCOMP.md` §3.6).
pub(crate) const fn syscall_rollback_value(
    abi: crate::trap::Abi,
    number: usize,
    args: &[u64; 6],
) -> isize {
    let _ = (abi, number);
    args[0] as isize
}

