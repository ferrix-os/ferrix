/// `AT_HWCAP` and `AT_HWCAP2` for a program started on this machine: what the
/// core's identification registers say it has, in the bits
/// `arch/arm/include/uapi/asm/hwcap.h` numbers. See `ferrix_linux_abi::hwcap`.
///
/// `AT_HWCAP2` is zero: on this architecture it holds only the `ARMv8` `AArch32`
/// cryptography bits, which no ARMv7-A core has.
pub(crate) fn user_hwcaps() -> (u64, u64) {
    use ferrix_linux_abi::hwcap::arm::{IdRegisters, hwcap};
    let (mvfr0, mvfr1) = cpu::user_fpu_features();
    let ids = IdRegisters {
        id_isar0: cpu::read_id_isar0(),
        id_mmfr0: cpu::read_id_mmfr0(),
        mvfr0,
        mvfr1,
    };
    (u64::from(hwcap(ids)), 0)
}

/// `AT_PLATFORM` for a program started on this machine.
///
/// `arch/arm/include/asm/elf.h` sets `ELF_PLATFORM` from the core's
/// architecture number in `CPUID`, as `"v6l"`, `"v7l"` and so on for a
/// little-endian kernel. Ferrix targets ARMv7-A only, on the DK1 board and
/// under QEMU's `virt` machine, so this is always `"v7l"` rather than a value
/// read out of an identification register the way `user_hwcaps` reads several.
/// There is no second ABI here, so `abi` is always the native one.
pub(crate) const fn user_platform(abi: crate::trap::Abi) -> Option<&'static [u8]> {
    let _ = abi;
    Some(b"v7l")
}

/// Make a freshly allocated user root usable.
///
/// Nothing to do to the tables: the kernel's half is reached through `TTBR1` and
/// a user root is only ever installed in `TTBR0`, so the two never share a
/// tree and a user root has nothing of the kernel's to be given. x86-64, which
/// keeps both halves in one root, is the architecture that exists for. What is
/// done is forget the root in every core's record of the space it last ran,
/// since a root reused for a new space is a new program; see
/// `crate::arch::speculation::forget_root`.
pub(crate) fn prepare_user_root(root: u64) {
    crate::arch::speculation::forget_root(root);
}

/// Translate this processor's lower half through the tables at `root`.
///
/// AArch64's version of this, in coprocessor 15's spelling and with one extra
/// thing to get right: `TTBCR.EPD0` is *set* on this architecture from the
/// moment the loader's identity map is dropped, so installing a user root is
/// not only a register write but the re-enabling of a translation regime. A
/// change that wrote `TTBR0` and left `EPD0` alone would fault on every user
/// access and look exactly like page tables that are wrong — which they would
/// not be. See [`cpu::write_ttbr0`].
///
/// # Safety
///
/// (TRANSLATE) `root` must root a live set of tables for the lower half, and they must
/// stay live until another root replaces them on this processor.
pub(crate) unsafe fn install_user_root(root: u64) {
    // SAFETY: (TRANSLATE) the caller guarantees the tables are live.
    unsafe { cpu::write_ttbr0(root) };
    cpu::flush_user_tlb();
    // The branch predictor invalidated, if this is another program's space
    // than the one this core last ran and the core is one that needs it.
    crate::arch::speculation::entered_space(root);
}

/// Stop translating the lower half at all.
///
/// What a processor picking up a kernel thread does; see AArch64's, whose
/// argument is the same one. `EPD0` governs walks and not the `TLB`, so the
/// cached user entries have to be invalidated as well.
///
/// # Safety
///
/// (TRANSLATE) Nothing may still need a user address on this processor.
pub(crate) unsafe fn uninstall_user_root() {
    // SAFETY: (TRANSLATE) the caller guarantees no user address is wanted; the kernel is
    // reached entirely through `TTBR1`.
    unsafe { cpu::disable_ttbr0() };
    cpu::flush_user_tlb();
}

/// Root of the loader's identity map, while it still exists.
///
/// `Some` for AArch64's reason: the identity map is a second translation
/// regime, under `TTBR0`, which nothing walking the kernel's own tables would
/// see — and the W^X sweep has to see everything the hardware can translate.
pub(crate) fn identity_root(view: &BootView<'_>) -> Option<u64> {
    let ttbr0 = view.raw().ttbr0_phys;
    (ttbr0 != 0 && !IDENTITY_DROPPED.load(Ordering::Relaxed)).then_some(ttbr0)
}

/// Set once [`drop_identity_map`] has run.
static IDENTITY_DROPPED: AtomicBool = AtomicBool::new(false);

/// True while anything the loader identity mapped still translates.
///
/// Read from the hardware for AArch64's reason: the identity map is the
/// `TTBR0` regime, which a walk of the kernel's tables never reaches. Live if
/// walks through `TTBR0` are enabled, or if the register still holds the
/// loader's root. And on a machine whose RAM is above the split, live while
/// the loader's own image still translates in the kernel's tree, where that
/// part of the identity map had to go.
pub(crate) fn identity_map_live(view: &BootView<'_>) -> bool {
    let loader_root = view.raw().ttbr0_phys;
    let regime = cpu::read_ttbcr() & cpu::TTBCR_EPD0 == 0
        || (loader_root != 0 && cpu::read_ttbr0() & cpu::TTBR_ADDRESS == loader_root);
    let alias = view
        .loader_alias()
        .is_some_and(|(base, _)| crate::mm::translate(base).is_some());
    regime || alias
}

/// True if the kernel faults when it writes through a read-only mapping.
///
/// Always, at PL1: the access permissions in a long descriptor bind the
/// kernel, and there is no switch to turn that off.
pub(crate) const fn kernel_write_protected() -> bool {
    true
}

/// Drop the loader's identity map, wherever the loader had to put it.
///
/// Usually that is the `TTBR0` regime and nothing else, which is switched off
/// rather than dismantled. On a machine whose RAM is above the split — the
/// STM32MP157, whose DDR starts at 3 GiB — `TTBR0` does not translate those
/// addresses at all, so the loader mapped its own image inside the kernel's
/// tree and that mapping is unmapped by hand first. It cannot be left: the
/// memory under it is the loader's, which [`crate::mm::reclaim_boot_memory`]
/// is about to hand to the frame allocator, and an executable mapping of
/// memory somebody else now owns is a worse version of the thing this function
/// exists to remove.
///
/// # Safety
///
/// (TRANSLATE) Nothing may still be executing or reading through the lower half of the
/// address space, or through that mapping. See [`cpu::disable_ttbr0`].
pub(crate) unsafe fn drop_identity_map(view: &BootView<'_>) {
    if let Some((base, len)) = view.loader_alias() {
        // The frames under it are the loader's own image and not this
        // mapping's to free; the memory map is what gives those back. A
        // failure here needs no report of its own, because the mapping is
        // writable and executable and the W^X sweep immediately after this is
        // exactly what notices one that survived.
        let _ = crate::mm::unmap_kernel(base, len, |_, _| {});
    }
    // SAFETY: (TRANSLATE) the caller guarantees the lower half is unused, and the kernel
    // has run entirely in the upper half since its first instruction.
    unsafe { cpu::disable_ttbr0() };
    IDENTITY_DROPPED.store(true, Ordering::Relaxed);
}

/// How this machine's PSCI firmware is called: 0 until the device tree has
/// been read, then 1 for `hvc` and 2 for `smc`.
static PSCI: AtomicU8 = AtomicU8::new(0);

/// How this machine's PSCI firmware is called, once [`init_interrupts`] has
/// read the device tree.
fn psci_conduit() -> Option<PsciConduit> {
    match PSCI.load(Ordering::Relaxed) {
        1 => Some(PsciConduit::Hvc),
        2 => Some(PsciConduit::Smc),
        _ => None,
    }
}

/// Where a backtrace starts: this function's frame pointer.
#[inline(always)]
pub(crate) fn frame_pointer() -> u64 {
    u64::from(cpu::frame_pointer())
}

/// Stop the machine, once the console has sent its last line.
pub(crate) fn shutdown() -> ! {
    crate::console::drain();
    if let Some(conduit) = psci_conduit() {
        cpu::psci_system_off(conduit);
    }
    halt()
}

/// Reset the machine, once the console has sent its last line.
///
/// A firmware without PSCI `SYSTEM_RESET` returns, and the machine is powered
/// off instead: one that stops when asked to come back is noticed, one that
/// carries on as though it had reset is not.
pub(crate) fn reset() -> ! {
    crate::console::drain();
    if let Some(conduit) = psci_conduit() {
        cpu::psci_system_reset(conduit);
    }
    crate::console::println!("  power    firmware did not reset the machine; powering off");
    shutdown()
}

