def read(path: Path) -> str:
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def write(path: Path, text: str) -> bool:
    """Write if different; returns whether the file changed."""
    if path.exists() and read(path) == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    return True


def is_stub(text: str) -> bool:
    return text.startswith(STUB_MARKER)


def repo_markdown(root: Path) -> list[str]:
    """The Markdown files whose links to docs/ROADMAP.md are rewritten."""
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--", "*.md"],
            check=True,
            capture_output=True,
        ).stdout.decode()
        files = [f for f in out.split("\0") if f]
        if not files:
            raise OSError
    except (OSError, subprocess.CalledProcessError):
        files = []
        for d, dirs, names in os.walk(root):
            dirs[:] = [x for x in dirs if x not in {".git", "target", "build", "book", ".claude"}]
            files += [rel(os.path.join(d, n), str(root)) for n in names if n.endswith(".md")]
    keep = []
    for f in sorted(set(files)):
        if f == ROADMAP or f.startswith(LINK_EXCLUDE):
            continue
        if f in LINK_TOP_FILES or f.split("/")[0] in LINK_DIRS:
            if (root / f).is_file():
                keep.append(f)
    return keep


def rewrite_repo_links(root: Path, amap: dict[str, tuple[str, str]], files=None) -> dict[str, int]:
    """Point Markdown links at docs/ROADMAP.md to the file their heading went to."""
    counts = {}
    for f in files if files is not None else repo_markdown(root):
        here = str(PurePosixPath(f).parent)
        here = "" if here == "." else here

        def fn(target: str, image: bool):
            if is_external(target):
                return None
            path, frag = split_target(target)
            if not path.endswith("ROADMAP.md") or path.startswith("/"):
                return None
            resolved = norm(PurePosixPath(here) / path) if here else norm(PurePosixPath(path))
            if resolved != ROADMAP and path != ROADMAP:
                return None
            if frag is None or frag == "":
                dest = f"{OUTDIR}/README.md"
                return rel(dest, here)
            if frag not in amap:
                print(f"  warning: {f}: no heading for #{frag} in the old roadmap; left as is")
                return None
            name, a = amap[frag]
            return f"{rel(f'{OUTDIR}/{name}', here)}#{a}"

        text = read(root / f)
        new, n = map_links(text, fn)
        if n:
            write(root / f, new)
            counts[f] = n
    return counts


def summary_order(summary: str) -> list[str]:
    """The section files SUMMARY.md lists, in order (not the overview or suffix)."""
    suffix = {f for _, f in SUFFIX_PAGES}
    out = []
    for m in re.finditer(r"^\s*- \[(?:[^\]\\]|\\.)*\]\(([^)]+)\)", summary, re.M):
        if m.group(1) not in suffix and m.group(1) != "README.md":
            out.append(m.group(1))
    return out


def h1_of(text: str) -> str:
    for _, level, title in headings(text):
        if level == 1:
            return title
    raise Failure("no H1")


def tree_sections(out: Path) -> list[tuple[str, str]]:
    """(the old `## ` heading, file) for each section SUMMARY.md lists."""
    summary = out / "SUMMARY.md"
    if not summary.exists():
        raise Failure(f"{summary} does not exist; run `split` first")
    result = []
    for fname in summary_order(read(summary)):
        p = out / fname
        if not p.exists():
            raise Failure(f"SUMMARY.md lists {fname}, which does not exist")
        try:
            result.append((h1_of(read(p)), fname))
        except Failure:
            raise Failure(f"{OUTDIR}/{fname} has no `# ` heading") from None
    return result


def index_outputs(root: Path) -> dict[str, str]:
    out = root / OUTDIR
    readme = read(out / "README.md")
    present = [f for _, f in SUFFIX_PAGES if (out / f).exists()]
    status_text = read(out / STATUS_PAGE) if (out / STATUS_PAGE).exists() else None
    summary, readme_new, stub = generated_parts(readme, tree_sections(out), present, status_text)
    return {f"{OUTDIR}/SUMMARY.md": summary, f"{OUTDIR}/README.md": readme_new, ROADMAP: stub}


def write_summary_order(out: Path, order: list[str]) -> None:
    """SUMMARY.md listing `order`; `index` then gives each entry its title."""
    entries = [(h1_of(read(out / f)), f, None) for f in order]
    present = [(t, f) for t, f in SUFFIX_PAGES if (out / f).exists()]
    write(out / "SUMMARY.md", summary_md(entries, present))


def cmd_index(root: Path) -> int:
    changed = [p for p, text in index_outputs(root).items() if write(root / p, text)]
    print("index: " + (", ".join(changed) + " updated" if changed else "up to date"))
    return 0


def split_outputs(text: str, present_suffix: list[str]) -> tuple[Roadmap, dict[str, str]]:
    road = load(text)
    files = {f"{OUTDIR}/{s.filename}": section_file_text(road, s) for s in road.sections}
    summary, readme, stub = generated_parts(
        overview_text(road), [(s.heading, s.filename) for s in road.sections], present_suffix
    )
    files[f"{OUTDIR}/SUMMARY.md"] = summary
    files[f"{OUTDIR}/README.md"] = readme
    files[ROADMAP] = stub
    return road, files


def cmd_split(root: Path) -> int:
    text = read(root / ROADMAP)
    if is_stub(text):
        print(f"split: {ROADMAP} is already the stub; nothing to do (run `index` to refresh)")
        return 0
    out = root / OUTDIR
    if (out / "SUMMARY.md").exists():
        raise Failure(
            f"{ROADMAP} is the whole roadmap but {OUTDIR}/SUMMARY.md exists too. "
            f"Remove the generated files first (`git rm` the ones SUMMARY.md lists, "
            f"SUMMARY.md and README.md) and run split again."
        )
    present = [f for _, f in SUFFIX_PAGES if (out / f).exists()]
    road, files = split_outputs(text, present)
    for p, t in files.items():
        write(root / p, t)
    counts = rewrite_repo_links(root, road.old_anchor)
    print(f"split: {len(road.sections)} sections and the overview into {OUTDIR}/; {ROADMAP} is now a stub")
    for f, n in counts.items():
        print(f"  rewrote {n} link{'s' if n != 1 else ''} in {f}")
    return 0


def join_text(root: Path) -> str:
    """The monolithic roadmap again, from the tree: the inverse of split."""
    out = root / OUTDIR
    secs = tree_sections(out)
    names = {f for _, f in secs}
    parts = [unrewrite_moved(demote(strip_index(read(out / "README.md")), preamble=True), names)]
    for _, f in secs:
        parts.append(unrewrite_moved(demote(read(out / f)), names))
    return "".join(parts)


