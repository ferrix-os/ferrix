#!/usr/bin/env python3
"""Split docs/ROADMAP.md into docs/roadmap/, one file a section, and keep it so.

    python3 tools/common/gen/split-roadmap.py [split]      # docs/ROADMAP.md -> docs/roadmap/
    python3 tools/common/gen/split-roadmap.py index        # refresh SUMMARY.md, the overview's
                                                      # stage index and the stub
    python3 tools/common/gen/split-roadmap.py check        # links, SUMMARY.md, index freshness
    python3 tools/common/gen/split-roadmap.py reapply [<old-tip>]
                                                      # carry a branch's edits to the old
                                                      # docs/ROADMAP.md into docs/roadmap/
    python3 tools/common/gen/split-roadmap.py join         # the monolithic roadmap, to stdout
    python3 tools/common/gen/split-roadmap.py mdbook ...   # mdBook preprocessor (book.toml)

The roadmap grew to 7,677 lines, which nobody reads from the top. `split` cuts it
at every `## ` heading, in order and byte for byte, with each heading promoted
one level so every file has one H1: `stage-NN-<slug>.md` for a numbered stage,
`<slug>.md` for the unnumbered sections. The preamble -- the rules, *Where it
stands*, the status table and the charts -- becomes the overview,
docs/roadmap/README.md, which ends in a stage index generated from the
headings. docs/ROADMAP.md becomes a stub that keeps every old `## ` heading,
so an old `ROADMAP.md#stage-7-...` link, or a "docs/ROADMAP.md stage 18" in a
comment, still lands on something that points onward. Links are rewritten:
relative links in the moved text get the extra `../`, `#anchor` links go to
the file the heading went to, and Markdown links to docs/ROADMAP.md elsewhere
in the repository go to the new file.

`split` is deterministic and does nothing on a docs/ROADMAP.md that is already
the stub, so it can be rerun on any `main`. `join` puts the pieces back
together (headings demoted, links reverted), which is what the round-trip test
checks against the original.

`reapply` is for a branch that edited the old file and was rebased onto the
split. It regenerates the split pieces from the branch's merge base and from
its old tip, and three-way merges the difference into each current file with
`git merge-file`; docs/roadmap/HOW-TO-EDIT.md has the recipe. Anything it
cannot place is printed, never dropped.

Standard library only, like the other gen-* scripts.
"""

