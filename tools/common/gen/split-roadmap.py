# ---------------------------------------------------------------------------
# Reading Markdown: fences, headings, anchors, links


FENCE = re.compile(r"^\s*(`{3,}|~{3,})")


def fence_flags(lines: list[str]) -> list[bool]:
    """For each line, whether it is inside (or delimits) a fenced code block."""
    flags = []
    opener = None
    for line in lines:
        m = FENCE.match(line)
        if opener is None:
            if m:
                opener = m.group(1)
                flags.append(True)
            else:
                flags.append(False)
        else:
            flags.append(True)
            if m and m.group(1)[0] == opener[0] and len(m.group(1)) >= len(opener):
                if not line.strip()[len(m.group(1)):].strip():
                    opener = None
    return flags


HEADING = re.compile(r"^(#{1,6})([ \t]+)(.*?)\s*$")


def headings(text: str) -> list[tuple[int, int, str]]:
    """(line index, level, text) of every ATX heading outside a fence."""
    lines = text.splitlines(keepends=True)
    out = []
    for i, (line, fenced) in enumerate(zip(lines, fence_flags(lines))):
        if fenced:
            continue
        m = HEADING.match(line)
        if m:
            title = re.sub(r"\s+#+\s*$", "", m.group(3))
            out.append((i, len(m.group(1)), title))
    return out


def heading_plain(title: str) -> str:
    """A heading's text as rendered: links to their text, markup removed."""
    t = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", title)
    t = re.sub(r"<[^>]+>", "", t)
    return t.replace("`", "").replace("*", "").replace("~~", "")


def anchor_of(title: str) -> str:
    """GitHub's anchor for a heading, which mdBook's ids agree with here."""
    t = heading_plain(title).strip().lower()
    t = re.sub(r"[^\w\- ]", "", t)
    return t.replace(" ", "-")


def anchors(text: str) -> list[str]:
    """Every heading's anchor, in order, with GitHub's -1, -2 for repeats."""
    seen: dict[str, int] = {}
    out = []
    for _, _, title in headings(text):
        base = anchor_of(title)
        n = seen.get(base, 0)
        seen[base] = n + 1
        out.append(base if n == 0 else f"{base}-{n}")
    return out


def shift_headings(text: str, by: int, min_level: int) -> str:
    """Move every heading of at least `min_level` by `by` levels."""
    lines = text.splitlines(keepends=True)
    for i, (line, fenced) in enumerate(zip(lines, fence_flags(lines))):
        if fenced:
            continue
        m = HEADING.match(line)
        if m and len(m.group(1)) >= min_level:
            level = len(m.group(1)) + by
            lines[i] = "#" * level + line[len(m.group(1)):]
    return "".join(lines)


def promote(text: str, preamble: bool = False) -> str:
    return shift_headings(text, -1, 3 if preamble else 2)


def demote(text: str, preamble: bool = False) -> str:
    return shift_headings(text, +1, 2 if preamble else 1)


CODE_SPAN = re.compile(r"(?<!`)(`+)(?!`)((?:(?!\n[ \t]*\n).)+?)(?<!`)\1(?!`)", re.S)
INLINE_LINK = re.compile(
    r"(!?)\[((?:[^\[\]]|\[[^\[\]]*\])*)\]\(\s*(<[^>\n]*>|[^()\s]*(?:\([^()\s]*\)[^()\s]*)*)"
    r"((?:\s+\"[^\"\n]*\")?\s*)\)"
)
REF_DEF = re.compile(r"^( {0,3}\[[^\]\n]+\]:[ \t]*)(\S+)", re.M)


def _chunks(text: str):
    """(is_code, text) runs: fenced blocks are code, the rest is prose."""
    lines = text.splitlines(keepends=True)
    run: list[str] = []
    state = None
    for line, fenced in zip(lines, fence_flags(lines)):
        if state is not None and fenced != state:
            yield state, "".join(run)
            run = []
        state = fenced
        run.append(line)
    if run:
        yield state, "".join(run)


def map_links(text: str, fn) -> tuple[str, int]:
    """Rewrite every link target outside code with fn(target, is_image).

    fn returns the new target, or None to leave it. Returns the new text and
    the number of targets changed.
    """
    out = []
    changed = 0
    for is_code, chunk in _chunks(text):
        if is_code:
            out.append(chunk)
            continue
        spans = [m.span() for m in CODE_SPAN.finditer(chunk)]

        def in_code(pos: int) -> bool:
            return any(a <= pos < b for a, b in spans)

        def sub_inline(m: re.Match) -> str:
            nonlocal changed
            if in_code(m.start()):
                return m.group(0)
            target = m.group(3)
            bare = target[1:-1] if target.startswith("<") else target
            new = fn(bare, m.group(1) == "!")
            if new is None or new == bare:
                return m.group(0)
            changed += 1
            start = m.start(3) - m.start()
            end = m.end(3) - m.start()
            whole = m.group(0)
            return whole[:start] + new + whole[end:]

        def sub_ref(m: re.Match) -> str:
            nonlocal changed
            if in_code(m.start()):
                return m.group(0)
            new = fn(m.group(2), False)
            if new is None or new == m.group(2):
                return m.group(0)
            changed += 1
            return m.group(1) + new

        chunk = INLINE_LINK.sub(sub_inline, chunk)
        chunk = REF_DEF.sub(sub_ref, chunk)
        out.append(chunk)
    return "".join(out), changed


def links(text: str) -> list[tuple[str, bool]]:
    """Every link target outside code, with whether it is an image."""
    found: list[tuple[str, bool]] = []

    def note(target: str, image: bool):
        found.append((target, image))
        return None

    map_links(text, note)
    return found


def is_external(target: str) -> bool:
    return bool(re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", target)) or target.startswith("//")


def split_target(target: str) -> tuple[str, str | None]:
    path, _, frag = target.partition("#")
    return path, (frag if "#" in target else None)


def norm(path: PurePosixPath) -> str:
    """A repository-relative path with `..` resolved, as a string."""
    return os.path.normpath(str(path)).replace(os.sep, "/")


def rel(to: str, from_dir: str) -> str:
    return os.path.relpath(to, from_dir or ".").replace(os.sep, "/")


# ---------------------------------------------------------------------------
# The split itself


@dataclass
class Section:
    heading: str  # the `## ` line's text
    text: str  # from the heading line to the next section, as in the old file
    start: int  # the heading's line in the old file, from 1
    filename: str = ""


@dataclass
class Roadmap:
    preamble: str
    sections: list[Section]
    old_anchor: dict[str, tuple[str, str]] = field(default_factory=dict)


def parse(text: str) -> tuple[str, list[Section]]:
    lines = text.splitlines(keepends=True)
    starts = [
        i
        for i, (line, fenced) in enumerate(zip(lines, fence_flags(lines)))
        if not fenced and line.startswith("## ")
    ]
    if not starts:
        raise Failure(f"{ROADMAP} has no `## ` section to split at")
    preamble = "".join(lines[: starts[0]])
    sections = []
    for n, s in enumerate(starts):
        end = starts[n + 1] if n + 1 < len(starts) else len(lines)
        heading = lines[s][3:].rstrip("\r\n").strip()
        sections.append(Section(heading, "".join(lines[s:end]), s + 1))
    return preamble, sections


STAGE = re.compile(r"^Stage\s+(\d+)\b")


def title_parts(heading: str) -> tuple[str, list[str], bool]:
    """A heading's name, its decorations after `·`, and whether it has ✅."""
    parts = [p.strip() for p in heading.split("·")]
    name = parts[0]
    done = "✅" in heading
    name = name.replace("✅", "").strip()
    decorations = [p.replace("✅", "").strip().strip("*").strip() for p in parts[1:]]
    return name, [d for d in decorations if d], done


def stage_number(heading: str) -> int | None:
    m = STAGE.match(heading)
    return int(m.group(1)) if m else None


def short_name(heading: str) -> str:
    """The section's name without `Stage N —`: what the index and slugs use."""
    name, _, _ = title_parts(heading)
    if stage_number(name) is not None:
        name = re.sub(r"^Stage\s+\d+\s*(—|--|-|:)?\s*", "", name)
    return name


def slug_words(text: str, limit: int) -> str:
    text = heading_plain(text).lower()
    text = re.sub(r"['’]s\b", "", text)
    text = re.sub(r"-(\w)\b", r"\1", text)  # ARMv7-A -> armv7a
    words = [w for w in re.split(r"[^a-z0-9]+", text) if w and w not in STOPWORDS]
    return "-".join(words[:limit])


def filename_for(heading: str) -> str:
    n = stage_number(heading)
    if n is not None:
        name = re.split(r"[:]", short_name(heading))[0]
        slug = slug_words(name, 4)
        return f"stage-{n:02d}-{slug}.md" if slug else f"stage-{n:02d}.md"
    name = re.split(r"—|--|,|:", short_name(heading))[0]
    return f"{slug_words(name, 2) or 'section'}.md"


def assign_filenames(sections: list[Section]) -> None:
    used: dict[str, int] = {}
    for s in sections:
        name = filename_for(s.heading)
        n = used.get(name, 0)
        used[name] = n + 1
        s.filename = name if n == 0 else name[:-3] + f"-{n + 1}.md"


def anchor_map(text: str, preamble: str, sections: list[Section]) -> dict[str, tuple[str, str]]:
    """Old anchor -> (new file, anchor in it), for every heading."""
    old = anchors(text)
    pieces = [("README.md", preamble, True)] + [(s.filename, s.text, False) for s in sections]
    new: list[tuple[str, str]] = []
    for name, piece, pre in pieces:
        new.extend((name, a) for a in anchors(promote(piece, pre)))
    if len(old) != len(new):
        raise Failure("heading count changed while splitting; this is a bug")
    return dict(zip(old, new))


def load(text: str) -> Roadmap:
    preamble, sections = parse(text)
    assign_filenames(sections)
    return Roadmap(preamble, sections, anchor_map(text, preamble, sections))


def rewrite_moved(text: str, own_file: str, amap: dict[str, tuple[str, str]]) -> str:
    """Links in text moved from docs/ to docs/roadmap/<own_file>."""

    def fn(target: str, image: bool):
        if is_external(target):
            return None
        path, frag = split_target(target)
        if path == "" and frag is not None:
            if frag not in amap:
                return None
            f, a = amap[frag]
            return f"#{a}" if f == own_file else f"{f}#{a}"
        if path.startswith("/"):
            return None
        resolved = norm(PurePosixPath("docs") / path)
        if resolved == ROADMAP:
            if frag is None:
                return "README.md" if own_file != "README.md" else "#"
            if frag in amap:
                f, a = amap[frag]
                return f"#{a}" if f == own_file else f"{f}#{a}"
            return None
        new = rel(resolved, OUTDIR)
        if path.endswith("/") and not new.endswith("/"):
            new += "/"
        return new + (f"#{frag}" if frag is not None else "")

    return map_links(text, fn)[0]


def unrewrite_moved(text: str, section_files: set[str]) -> str:
    """The inverse of rewrite_moved, for `join`."""

    def fn(target: str, image: bool):
        if is_external(target):
            return None
        path, frag = split_target(target)
        if path == "" or path.startswith("/"):
            return None
        if path in section_files or path == "README.md":
            return f"#{frag}" if frag is not None else "#"
        resolved = norm(PurePosixPath(OUTDIR) / path)
        new = rel(resolved, "docs")
        if path.endswith("/") and not new.endswith("/"):
            new += "/"
        return new + (f"#{frag}" if frag is not None else "")

    return map_links(text, fn)[0]


def section_file_text(road: Roadmap, s: Section) -> str:
    return rewrite_moved(promote(s.text), s.filename, road.old_anchor)


def overview_text(road: Roadmap) -> str:
    """README.md without its generated stage index."""
    return rewrite_moved(promote(road.preamble, preamble=True), "README.md", road.old_anchor)


# ---------------------------------------------------------------------------
# The generated parts: SUMMARY.md, the overview's stage index, the stub


def status_rows(overview: str) -> list[tuple[str, str]]:
    """(what, current state) of each row of a status table (status.md's, or the overview's before it had one)."""
    rows = []
    in_table = False
    for line in overview.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.startswith("|") and len(cells) >= 3 and cells[0].lower() == "what":
            in_table = True
            continue
        if in_table:
            if not line.startswith("|"):
                in_table = False
                continue
            if set(line.replace("|", "").strip()) <= set("-: "):
                continue
            rows.append((cells[0], cells[-1]))
    return rows


def classify_state(state: str) -> str | None:
    s = state.lower().strip().strip("*").strip()
    if s.startswith("done"):
        return DONE
    if s.startswith(("in progress", "under way", "partially")):
        return PROGRESS
    if s.startswith("not started"):
        return NOT_STARTED
    if s.startswith("planned"):
        return PLANNED
    # A sentence rather than a state: "init done (L1 to L10); phase 1 is not
    # started" is a stage part of the way through.
    if re.search(r"\b(done|under way|in progress|landed|met)\b", s):
        return PROGRESS
    return None


def rows_for(heading: str, rows: list[tuple[str, str]]) -> list[str]:
    n = stage_number(heading)
    key = re.split(r"—|--|,|:", short_name(heading))[0].strip().lower()
    found = []
    for what, state in rows:
        w = re.sub(r"~~", "", what).strip()
        if n is not None:
            m = STAGE.match(w)
            if not m or int(m.group(1)) != n:
                continue
        elif not key or not w.lower().startswith(key):
            continue
        c = classify_state(state)
        if c:
            found.append(c)
    return found


def status_of(heading: str, rows: list[tuple[str, str]]) -> str | None:
    """✅ or a `done` decoration first, then the status table's rows."""
    _, decorations, done = title_parts(heading)
    if done or any(d.lower().startswith("done") for d in decorations):
        return DONE
    states = rows_for(heading, rows)
    if states:
        if all(s == DONE for s in states):
            return DONE
        if PROGRESS in states or DONE in states:
            return PROGRESS
        if all(s == PLANNED for s in states):
            return PLANNED
        return NOT_STARTED
    return NOT_STARTED if stage_number(heading) is not None else None


def display_title(heading: str, status: str | None) -> str:
    name, _, _ = title_parts(heading)
    return f"{MARK[status] if status else NO_MARK} {name}"


def summary_md(entries: list[tuple[str, str, str | None]], suffix: list[tuple[str, str]]) -> str:
    out = ["# Summary", "", "[Overview](README.md)", ""]
    for heading, fname, status in entries:
        title = display_title(heading, status).replace("[", "\\[").replace("]", "\\]")
        out.append(f"- [{title}]({fname})")
    if suffix:
        out += ["", "---", ""]
        out += [f"[{t}]({f})" for t, f in suffix]
    return "\n".join(out) + "\n"


def index_block(entries: list[tuple[str, str, str | None]]) -> str:
    out = [
        INDEX_BEGIN,
        "",
        "## The stages",
        "",
        "One file a section, in the roadmap's order. The status is the heading's",
        "✅ or `done`, and otherwise the status table's rows for that stage;",
        "the size is what the heading says. [HOW-TO-EDIT.md](HOW-TO-EDIT.md) says",
        "how to change a stage, add one, or carry a branch's edits of the old",
        "single file across.",
        "",
        "| Stage | Section | Status | Size, as the heading gives it |",
        "|---|---|---|---|",
    ]
    for heading, fname, status in entries:
        n = stage_number(heading)
        name = short_name(heading).replace("|", "\\|")
        _, decorations, _ = title_parts(heading)
        size = "; ".join(decorations).replace("|", "\\|") or ""
        out.append(
            f"| {n if n is not None else ''} | [{name}]({fname}) | "
            f"{STATUS_LABEL.get(status, '') if status else ''} | {size} |"
        )
    out += ["", INDEX_END]
    return "\n".join(out) + "\n"


def stub_md(h1: str, entries: list[tuple[str, str, str | None]]) -> str:
    out = [
        STUB_MARKER,
        "",
        h1.rstrip("\n"),
        "",
        "The roadmap now lives in [`docs/roadmap/`](roadmap/README.md), one file a",
        "stage. Its overview -- where it stands in short, the forecast, and the",
        "index of stages -- is",
        "[`docs/roadmap/README.md`](roadmap/README.md), and",
        "`tools/common/gen/build-roadmap-book.sh` builds the whole of it into a website.",
        "Edit the stage's file, not this one; each heading below is kept so that",
        "an old link to it still lands here, and points to where it went.",
        "",
    ]
    for heading, fname, _ in entries:
        out += [f"## {heading}", "", f"Now [`docs/roadmap/{fname}`](roadmap/{fname}).", ""]
    return "\n".join(out)


def strip_index(readme: str) -> str:
    i = readme.find(INDEX_BEGIN)
    return readme if i < 0 else readme[:i]


def generated_parts(
    overview: str,
    sections: list[tuple[str, str]],
    suffix_present: list[str],
    status_text: str | None = None,
):
    """SUMMARY.md, README.md and the stub, from the overview and (heading, file)s."""
    rows = status_rows(status_text if status_text is not None else overview)
    entries = [(h, f, status_of(h, rows)) for h, f in sections]
    suffix = [(t, f) for t, f in SUFFIX_PAGES if f in suffix_present]
    h1 = next((ln for ln in overview.splitlines() if ln.startswith("# ")), "# Roadmap")
    return (
        summary_md(entries, suffix),
        strip_index(overview) + index_block(entries),
        stub_md(h1, entries),
    )


