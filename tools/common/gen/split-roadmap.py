def check(root: Path) -> tuple[list[str], int]:
    problems: list[str] = []
    out = root / OUTDIR
    if not (out / "SUMMARY.md").exists():
        return [f"{OUTDIR}/SUMMARY.md does not exist"], 0
    if not is_stub(read(root / ROADMAP)):
        problems.append(f"{ROADMAP} is not the stub; run split")

    pages = sorted(
        str(p.relative_to(out)).replace(os.sep, "/")
        for p in out.rglob("*.md")
        if not any(part in {"book", "theme"} for part in p.relative_to(out).parts)
    )
    summary = read(out / "SUMMARY.md")
    listed = [t for t, _ in links(summary)]
    for page in pages:
        if page != "SUMMARY.md" and page not in listed:
            problems.append(f"{OUTDIR}/{page} is not listed in SUMMARY.md")
    for t in listed:
        if not (out / t).exists():
            problems.append(f"SUMMARY.md lists {t}, which does not exist")

    anchor_cache: dict[str, set[str]] = {}

    def anchors_in(path: str) -> set[str]:
        if path not in anchor_cache:
            anchor_cache[path] = set(anchors(read(root / path)))
        return anchor_cache[path]

    def check_file(f: str, only_roadmap_targets: bool) -> int:
        here = str(PurePosixPath(f).parent)
        n = 0
        for target, _ in links(read(root / f)):
            if is_external(target):
                continue
            path, frag = split_target(target)
            if path.startswith("/"):
                continue
            dest = norm(PurePosixPath(here) / path) if path else f
            if only_roadmap_targets and not (dest == ROADMAP or dest.startswith(OUTDIR + "/") or dest == OUTDIR):
                continue
            n += 1
            if not (root / dest).exists():
                problems.append(f"{f}: link to {target}: {dest} does not exist")
                continue
            if frag and dest.endswith(".md") and (root / dest).is_file():
                if frag not in anchors_in(dest):
                    problems.append(f"{f}: link to {target}: no heading #{frag} in {dest}")
        return n

    count = 0
    for page in pages:
        count += check_file(f"{OUTDIR}/{page}", False)
    count += check_file(ROADMAP, False)
    for f in repo_markdown(root):
        count += check_file(f, True)

    try:
        for p, text in index_outputs(root).items():
            if read(root / p) != text:
                problems.append(f"{p} is stale: run `python3 tools/common/gen/split-roadmap.py index`")
    except Failure as e:
        problems.append(str(e))

    for page in pages:
        text = read(out / page)
        if re.search(r"^(<<<<<<<|>>>>>>>) ", text, re.M):
            problems.append(f"{OUTDIR}/{page} has conflict markers")
    return problems, count


def cmd_check(root: Path) -> int:
    problems, count = check(root)
    for p in problems:
        print(f"  {p}")
    if problems:
        print(f"check: {len(problems)} problem{'s' if len(problems) != 1 else ''}")
        return 1
    print(f"check: {OUTDIR}/ and its links are consistent ({count} links resolved)")
    return 0


