def git(root: Path, *args: str, check_ok: bool = True) -> str:
    r = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)
    if check_ok and r.returncode != 0:
        raise Failure(f"git {' '.join(args)}: {r.stderr.strip()}")
    return r.stdout


def git_show(root: Path, rev: str, path: str) -> str:
    r = subprocess.run(["git", "-C", str(root), "show", f"{rev}:{path}"], capture_output=True)
    if r.returncode != 0:
        raise Failure(f"{rev} has no {path}")
    return r.stdout.decode("utf-8")


def merge3(current: str, base: str, theirs: str, label: str) -> tuple[str, int]:
    with tempfile.TemporaryDirectory(prefix="split-roadmap-") as d:
        paths = []
        for name, text in (("current", current), ("base", base), ("theirs", theirs)):
            p = os.path.join(d, name)
            with open(p, "w", encoding="utf-8", newline="") as f:
                f.write(text)
            paths.append(p)
        r = subprocess.run(
            ["git", "merge-file", "-p", "-L", f"{label} (now)", "-L", "merge base", "-L", f"{label} (branch)", *paths],
            capture_output=True,
        )
        if r.returncode < 0 or r.returncode > 127:
            raise Failure(f"git merge-file failed on {label}: {r.stderr.decode()}")
        return r.stdout.decode("utf-8"), r.returncode


def pieces(text: str) -> tuple[Roadmap, dict[str, tuple[str, int, int, str]]]:
    """name -> (content, first old line, last old line, heading) for each piece."""
    road = load(text)
    first = road.sections[0].start
    out = {"README.md": (overview_text(road), 1, first - 1, "the preamble")}
    for i, s in enumerate(road.sections):
        last = (road.sections[i + 1].start - 1) if i + 1 < len(road.sections) else len(text.splitlines())
        out[s.filename] = (section_file_text(road, s), s.start, last, f"## {s.heading}")
    return road, out


def hunk_lines(a: str, b: str, offset: int) -> list[str]:
    out = []
    sm = difflib.SequenceMatcher(None, a.splitlines(), b.splitlines(), autojunk=False)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            continue
        what = {"replace": "changes", "delete": "removes", "insert": "adds"}[tag]
        if tag == "insert":
            where = f"after old line {offset + i1 - 1}"
        else:
            where = f"old lines {offset + i1}-{offset + i2 - 1}"
        n = (j2 - j1) if tag != "delete" else (i2 - i1)
        out.append(f"{what} {n} line{'s' if n != 1 else ''} at {where}")
    return out


def cmd_reapply(root: Path, old_tip: str) -> int:
    out = root / OUTDIR
    if not is_stub(read(root / ROADMAP)) or not (out / "SUMMARY.md").exists():
        raise Failure(
            f"{ROADMAP} is not the stub here: rebase onto a main that has {OUTDIR}/ first, "
            "then run reapply with the branch's old tip"
        )
    for state in ("rebase-merge", "rebase-apply"):
        if Path(root, git(root, "rev-parse", "--git-path", state).strip()).exists():
            raise Failure("a rebase is still in progress: finish it (git rebase --continue) first")
    tip = git(root, "rev-parse", "--verify", f"{old_tip}^{{commit}}").strip()
    base = git(root, "merge-base", tip, "HEAD").strip()
    base_text = git_show(root, base, ROADMAP)
    tip_text = git_show(root, tip, ROADMAP)
    if is_stub(tip_text) or is_stub(base_text):
        raise Failure(f"{old_tip} already has the split roadmap; there is nothing of the old file to carry")
    print(f"reapply: {ROADMAP} from merge base {base[:10]} to {old_tip} ({tip[:10]})")
    if base_text == tip_text:
        print("reapply: the branch did not change the roadmap; nothing to do")
        return 0

    _, pb = pieces(base_text)
    road_t, pt = pieces(tip_text)
    order = summary_order(read(out / "SUMMARY.md"))
    tip_order = [s.filename for s in road_t.sections]
    trouble = 0
    touched = []

    for name in list(dict.fromkeys(list(pb) + list(pt))):
        b = pb.get(name)
        t = pt.get(name)
        if b and t and b[0] == t[0]:
            continue
        where_path = out / name
        dest = f"{OUTDIR}/{name}"
        info = t or b
        assert info is not None
        print(f"\n  {info[3]}  (old lines {info[1]}-{info[2]})  ->  {dest}")
        if b and t:
            for h in hunk_lines(b[0], t[0], b[1]):
                print(f"    {h}")
        if name == "README.md":
            now = read(where_path)
            block = now[len(strip_index(now)):]
            merged, conflicts = merge3(strip_index(now), b[0], t[0], dest)  # type: ignore[index]
            write(where_path, merged + block)
        elif b is None:
            assert t is not None
            if where_path.exists() and read(where_path) != t[0]:
                print(f"    CANNOT PLACE: the branch adds this section, and {dest} already exists "
                      "with other text. The branch's version:")
                sys.stdout.write("".join("      " + ln for ln in t[0].splitlines(keepends=True)))
                trouble += 1
                continue
            write(where_path, t[0])
            if name not in order:
                i = tip_order.index(name)
                prev = next((p for p in reversed(tip_order[:i]) if p in order), None)
                order.insert(order.index(prev) + 1 if prev else 0, name)
            print("    new section: written, and listed in SUMMARY.md")
            touched.append(dest)
            continue
        elif t is None:
            if where_path.exists() and read(where_path) == b[0]:
                where_path.unlink()
                order = [o for o in order if o != name]
                print("    the branch removes this section: removed")
                touched.append(dest)
            else:
                print(f"    CANNOT PLACE: the branch removes this section, and {dest} has changed "
                      "since; remove it by hand if it should go")
                trouble += 1
            continue
        elif not where_path.exists():
            print(f"    CANNOT PLACE: {dest} does not exist now (the section was renamed or "
                  "removed on main). Apply this by hand:")
            diff = difflib.unified_diff(
                b[0].splitlines(keepends=True), t[0].splitlines(keepends=True),
                f"a/{dest}", f"b/{dest}",
            )
            sys.stdout.write("".join("      " + ln for ln in diff))
            trouble += 1
            continue
        else:
            merged, conflicts = merge3(read(where_path), b[0], t[0], dest)
            write(where_path, merged)
        touched.append(dest)
        if conflicts:
            print(f"    CONFLICT: {conflicts} conflict{'s' if conflicts != 1 else ''} left marked in {dest}")
            trouble += 1
        else:
            print("    merged cleanly")

    if summary_order(read(out / "SUMMARY.md")) != order:
        write_summary_order(out, order)
    cmd_index(root)
    counts = rewrite_repo_links(root, road_t.old_anchor)
    for f, n in counts.items():
        print(f"  rewrote {n} link{'s' if n != 1 else ''} to the old roadmap in {f}")
    if trouble:
        print(f"\nreapply: {trouble} piece{'s' if trouble != 1 else ''} need a hand (above); "
              "resolve them, then run `index` and `check`")
        return 1
    print(f"\nreapply: carried into {', '.join(touched) or 'nothing'}; review with `git diff`, "
          "then run `check`")
    return 0


