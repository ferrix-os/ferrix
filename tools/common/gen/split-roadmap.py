def main(argv: list[str]) -> int:
    if argv and argv[0] == "mdbook":
        return cmd_mdbook(argv[1:])
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path, default=ROOT, help="repository root (default: this checkout)")
    sub = ap.add_subparsers(dest="cmd")
    sub.add_parser("split", help="split docs/ROADMAP.md into docs/roadmap/ (the default)")
    sub.add_parser("index", help="regenerate SUMMARY.md, the overview's stage index and the stub")
    sub.add_parser("check", help="check SUMMARY.md, every link and anchor, and the index")
    sub.add_parser("join", help="print the monolithic roadmap, reassembled")
    r = sub.add_parser("reapply", help="carry a rebased branch's edits of the old file across")
    r.add_argument("old_tip", nargs="?", default="ORIG_HEAD", help="the branch's tip before the rebase")
    args = ap.parse_args(argv)
    root = args.root.resolve()
    try:
        if args.cmd in (None, "split"):
            return cmd_split(root)
        if args.cmd == "index":
            return cmd_index(root)
        if args.cmd == "check":
            return cmd_check(root)
        if args.cmd == "join":
            sys.stdout.write(join_text(root))
            return 0
        if args.cmd == "reapply":
            return cmd_reapply(root, args.old_tip)
    except Failure as e:
        print(f"split-roadmap: {e}", file=sys.stderr)
        return 2
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
