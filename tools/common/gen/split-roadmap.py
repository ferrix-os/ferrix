def cmd_mdbook(argv: list[str]) -> int:
    """Make links that leave the book work on the website.

    A link to `../GPU.md` is right in the repository and nowhere on the site,
    so on the site it goes to the repository's web view instead, and an image
    from `docs/img/` is inlined, which keeps print.html one file.
    """
    if argv and argv[0] == "supports":
        return 0
    context, book = json.load(sys.stdin)
    cfg = context.get("config", {})
    book_root = Path(context["root"]).resolve()
    src = (book_root / cfg.get("book", {}).get("src", ".")).resolve()
    repo_url = cfg.get("output", {}).get("html", {}).get("git-repository-url", "")
    repo_root = ROOT

    def visit(node):
        if isinstance(node, dict):
            ch = node.get("Chapter")
            if isinstance(ch, dict) and isinstance(ch.get("content"), str):
                here = (src / (ch.get("path") or ch.get("source_path") or "x")).parent
                ch["content"] = map_links(ch["content"], lambda t, img: outside(t, img, here))[0]
            for v in node.values():
                visit(v)
        elif isinstance(node, list):
            for v in node:
                visit(v)

    def outside(target: str, image: bool, here: Path):
        if is_external(target):
            return None
        path, frag = split_target(target)
        if not path or path.startswith("/"):
            return None
        dest = Path(os.path.normpath(here / path))
        if dest == src or src in dest.parents:
            return None
        if image and dest.is_file():
            mime = {".svg": "image/svg+xml", ".png": "image/png", ".jpg": "image/jpeg"}.get(
                dest.suffix.lower(), "application/octet-stream"
            )
            return f"data:{mime};base64," + base64.b64encode(dest.read_bytes()).decode()
        if repo_url and repo_root in dest.parents:
            kind = "tree" if dest.is_dir() else "blob"
            r = str(dest.relative_to(repo_root)).replace(os.sep, "/")
            return f"{repo_url.rstrip('/')}/{kind}/main/{r}" + (f"#{frag}" if frag else "")
        return None

    visit(book)
    json.dump(book, sys.stdout)
    return 0


