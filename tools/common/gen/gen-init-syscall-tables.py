#!/usr/bin/env python3
"""Generate the system call, errno and group tables init's filters are built from.

`SystemCallFilter=` names system calls and systemd's groups of them, and a
seccomp filter compares numbers. The numbers differ per ABI, and a wrong one
is a filter that lets through the call it was asked to stop, so they are
never typed: this reads them from Linux's own UAPI headers, and the groups
from systemd's own listing, all committed verbatim in
`src/lib/init/svc/data/`:

* `unistd_x86_64.h`, `unistd_i386.h`, `unistd_aarch64.h`: Linux's generated
  tables, `#define __NR_<name> <number>` (QEMU's `linux-headers`, Linux
  v6.12-rc5).
* `unistd_arm_common.h` and `unistd_arm.h`: ARM EABI, where
  `__NR_SYSCALL_BASE` is 0, and the private calls from `__ARM_NR_BASE`
  (0x0f0000), named as libseccomp names them (`set_tls`, `cacheflush`, ...).
* `errno-base.h`, `errno.h`: `asm-generic`'s errno numbers, which x86,
  ARM and AArch64 all use (Linux 7.0's, from the host's linux-libc-dev).
* `systemd-259-syscall-filter.txt`: `systemd-analyze syscall-filter` of
  systemd 259, every `@group` and its members.

It writes `src/lib/init/svc/src/filter/tables.rs`. The output is committed,
and `--check` regenerates into memory and compares.

Usage:
    python3 tools/common/gen/gen-init-syscall-tables.py           # write
    python3 tools/common/gen/gen-init-syscall-tables.py --check   # fail if stale
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DATA = ROOT / "src/lib/init/svc/data"
OUT = ROOT / "src/lib/init/svc/src/filter/tables.rs"

DEFINE = re.compile(r"^#define\s+__NR_(\w+)\s+(.+?)\s*$")
ARM_PRIVATE = re.compile(r"^#define\s+__ARM_NR_(\w+)\s+\(__ARM_NR_BASE\s*\+\s*(\d+)\)")
ERRNO = re.compile(r"^#define\s+(E\w+)\s+(\w+)\s*(/\*.*)?$")


def flat_table(path: Path) -> dict[str, int]:
    """`#define __NR_x n`, and ARM's `(__NR_SYSCALL_BASE + n)` with base 0."""
    table: dict[str, int] = {}
    for line in path.read_text().splitlines():
        match = DEFINE.match(line)
        if not match:
            continue
        name, value = match.groups()
        if name in ("syscalls", "SYSCALL_BASE", "OABI_SYSCALL_BASE"):
            continue
        value = value.strip("()").replace("__NR_SYSCALL_BASE", "0")
        number = eval(value, {"__builtins__": {}}, {})  # digits and + only
        table[name] = int(number)
    return table


def arm_table() -> dict[str, int]:
    table = flat_table(DATA / "unistd_arm_common.h")
    for line in (DATA / "unistd_arm.h").read_text().splitlines():
        match = ARM_PRIVATE.match(line)
        if match:
            table[match.group(1)] = 0x0F0000 + int(match.group(2))
    return table


def errno_table() -> dict[str, int]:
    raw: dict[str, str] = {}
    for name in ("errno-base.h", "errno.h"):
        for line in (DATA / name).read_text().splitlines():
            match = ERRNO.match(line)
            if match:
                raw[match.group(1)] = match.group(2)
    table: dict[str, int] = {}
    for name, value in raw.items():
        while not value.isdigit():
            value = raw[value]  # EWOULDBLOCK is EAGAIN, EDEADLOCK EDEADLK
        table[name] = int(value)
    return table


def groups() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    current = None
    for line in (DATA / "systemd-259-syscall-filter.txt").read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line.startswith(" "):
            current = line.strip().removeprefix("@")
            out[current] = []
            continue
        if current is not None:
            out[current].append(line.strip())
    # @known is every call systemd knows; init takes it as every call the
    # ABI's table has, which is what a filter can name.
    out.pop("known", None)
    return out


def digest() -> str:
    h = hashlib.sha256()
    for path in sorted(DATA.iterdir()):
        h.update(path.name.encode())
        h.update(path.read_bytes())
    return h.hexdigest()


def render() -> str:
    lines = [
        "// @generated by tools/common/gen/gen-init-syscall-tables.py from src/lib/init/svc/data/.",
        "// Do not edit: regenerate with the script, and check with `--check`.",
        f"// Inputs' SHA-256: {digest()}",
        "",
        "//! The system call, errno and group tables, generated.",
        "",
    ]

    def table(name: str, doc: str, rows: dict[str, int]) -> None:
        lines.append(f"/// {doc}, by name.")
        lines.append(f"pub(crate) const {name}: &[(&str, u32)] = &[")
        for key in sorted(rows):
            lines.append(f'    ("{key}", {rows[key]}),')
        lines.append("];")
        lines.append("")

    table("X86_64", "x86-64's system calls (`unistd_64.h`)", flat_table(DATA / "unistd_x86_64.h"))
    table("I386", "i386's, as x86-64's `int $0x80` takes them (`unistd_32.h`)", flat_table(DATA / "unistd_i386.h"))
    table("AARCH64", "AArch64's (`asm-arm64/unistd_64.h`)", flat_table(DATA / "unistd_aarch64.h"))
    table("ARM", "ARM EABI's, with the private calls from 0x0f0000", arm_table())
    table("ERRNO", "The errno numbers (`asm-generic`)", errno_table())
    lines.append("/// systemd 259's system call groups, without the `@`, and their")
    lines.append("/// members; a member starting with `@` is another group.")
    lines.append("pub(crate) const GROUPS: &[(&str, &[&str])] = &[")
    for name, members in sorted(groups().items()):
        lines.append(f'    ("{name}", &[')
        for member in members:
            lines.append(f'        "{member}",')
        lines.append("    ]),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run {Path(__file__).relative_to(ROOT)}")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
