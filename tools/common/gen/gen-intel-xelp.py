#!/usr/bin/env python3
"""Turn i915's tables into the Rust tables `ferrix-intel-xelp` reads.

`docs/INTEL-GPU.md` §3.6: the Intel driver follows Linux's i915 file by file,
and its tables are i915's, not retyped. Retyping the forcewake ranges, the
shadowed registers, the context image's register offsets and the MOCS table
would be hundreds of numbers nobody could review against Linux. So the i915
files the tables live in are vendored, unchanged, under
`src/lib/drivers/gpu/intel-xelp/i915/` (MIT, Linux v7.0, see its README),
and this script reads the C initialisers there and writes one Rust module
per C file under `src/generated/`, each carrying that file's copyright
notice and each entry the C text it came from.

Only what the C macros compute is evaluated here (`GEN_FW_RANGE`, the
`NOP`/`LRI`/`REG`/`REG16` byte code, `MOCS_ENTRY` and its `LE_*`/`L3_*`
fields, `INTEL_VGA_DEVICE` lists). Anything the script does not recognise
stops it with the line, so a later Linux whose tables change shape fails
loudly rather than producing a quietly different table.

The output is committed, and `--check` regenerates it into memory and
compares, as `gen-wayland-protocol.py` does.

Usage:
    python3 tools/common/gen/gen-intel-xelp.py           # write the modules
    python3 tools/common/gen/gen-intel-xelp.py --check   # fail if they are stale
"""

import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent.parent
CRATE = ROOT / "src" / "lib" / "drivers" / "gpu" / "intel-xelp"
I915 = CRATE / "i915"
OUT = CRATE / "src" / "generated"


def fail(message):
    sys.exit(f"gen-intel-xelp: {message}")


# The MIT permission notice as i915's files that spell it out carry it
# (intel_uncore.c). A file tagged only `SPDX-License-Identifier: MIT` is under
# the same terms (Linux's LICENSES/preferred/MIT), and the notice has to travel
# with the copy, so it is written out after that file's own copyright lines.
